CREATE OR REPLACE FUNCTION public.kandid_resolve_program_catalog_id(p_program text)
RETURNS bigint LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog AS $$
  SELECT CASE WHEN count(DISTINCT p.id) = 1 THEN min(p.id)::bigint ELSE NULL::bigint END
  FROM public.programs p
  WHERE upper(trim(p.code)) = upper(trim(coalesce(p_program, '')))
     OR upper(trim(p.name)) = upper(trim(coalesce(p_program, '')))
$$;
ALTER FUNCTION public.kandid_resolve_program_catalog_id(text) OWNER TO postgres;
REVOKE ALL ON FUNCTION public.kandid_resolve_program_catalog_id(text) FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.kandid_check_student_organization_admission(
  p_student_id integer, p_organization_id integer, p_academic_term_id integer
) RETURNS TABLE (allowed boolean, reason text, target_organization_type text, academic_term_id integer)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE active_id integer; active_count integer; org_type text; enrollment_program text;
BEGIN
  SELECT count(*)::integer, min(t.id) INTO active_count, active_id FROM public.academic_terms t WHERE t.status = 'active';
  SELECT o.organization_type INTO org_type FROM public.organizations o WHERE o.id = p_organization_id;
  SELECT e.program INTO enrollment_program FROM public.student_term_enrollments e
    WHERE e.student_id = p_student_id AND e.academic_term_id = p_academic_term_id AND e.enrollment_status = 'enrolled';
  allowed := false; reason := 'ACTIVE_TERM_UNAVAILABLE'; target_organization_type := org_type; academic_term_id := p_academic_term_id;
  IF active_count <> 1 OR active_id <> p_academic_term_id THEN reason := 'TERM_NOT_ACTIVE';
  ELSIF enrollment_program IS NULL THEN reason := 'NOT_CURRENTLY_ENROLLED';
  ELSIF org_type = 'non_departmental' OR EXISTS (
    SELECT 1 FROM public.organization_programs op
      JOIN public.programs p ON p.id = op.program_id
      WHERE op.organization_id = p_organization_id
        AND upper(trim(p.code)) = upper(trim(enrollment_program))
  ) THEN allowed := true; reason := 'ALLOWED';
  ELSE reason := 'PROGRAM_NOT_ELIGIBLE_FOR_ORGANIZATION'; END IF;
  RETURN NEXT;
END $$;
ALTER FUNCTION public.kandid_check_student_organization_admission(integer, integer, integer) OWNER TO postgres;
REVOKE ALL ON FUNCTION public.kandid_check_student_organization_admission(integer, integer, integer) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.kandid_check_student_organization_admission(integer, integer, integer) TO service_role;

