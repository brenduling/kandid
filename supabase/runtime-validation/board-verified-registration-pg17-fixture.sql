CREATE TABLE public.student_term_enrollments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id integer NOT NULL REFERENCES public.students(id),
  academic_term_id integer NOT NULL REFERENCES public.academic_terms(id),
  program text,
  year_level integer,
  is_shs boolean NOT NULL DEFAULT false,
  enrollment_status text NOT NULL DEFAULT 'enrolled' CHECK (enrollment_status IN ('enrolled', 'not_in_masterlist')),
  source text NOT NULL DEFAULT 'masterlist' CHECK (source IN ('masterlist', 'manual', 'migration')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT student_term_enrollments_unique_student_term UNIQUE (student_id, academic_term_id)
);
CREATE TABLE public.student_organization_terms (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id integer NOT NULL REFERENCES public.students(id),
  organization_id integer NOT NULL REFERENCES public.organizations(id),
  academic_term_id integer NOT NULL REFERENCES public.academic_terms(id),
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'removed')),
  source text NOT NULL DEFAULT 'system' CHECK (source IN ('masterlist', 'manual', 'board_csv', 'student_setup', 'program_sync', 'system')),
  removed_by integer,
  removed_at timestamptz,
  removal_reason text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT student_organization_terms_removed_fields_check CHECK (
    (status = 'active' AND removed_by IS NULL AND removed_at IS NULL)
    OR (status = 'removed' AND removed_at IS NOT NULL)
  ),
  CONSTRAINT student_organization_terms_unique_student_org_term UNIQUE (student_id, organization_id, academic_term_id)
