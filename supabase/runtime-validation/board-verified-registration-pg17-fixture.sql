CREATE TABLE public.organizations (
  id integer PRIMARY KEY,
  name text NOT NULL,
  organization_type text NOT NULL CHECK (organization_type IN ('departmental', 'non_departmental')),
  membership_scope text NOT NULL CHECK (membership_scope IN ('program', 'institution', 'manual'))
);
CREATE TABLE public.programs (
  id bigint PRIMARY KEY,
  code text NOT NULL UNIQUE,
  name text NOT NULL
);
CREATE TABLE public.organization_programs (
  organization_id integer NOT NULL REFERENCES public.organizations(id),
  program_id bigint NOT NULL REFERENCES public.programs(id),
  PRIMARY KEY (organization_id, program_id)
);
