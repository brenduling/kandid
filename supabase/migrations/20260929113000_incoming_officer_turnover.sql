create or replace function public.kandid_release_officer_leadership(p_organization_id bigint)
returns jsonb
language plpgsql
volatile
security definer
set search_path = pg_catalog
as $function$
declare
  organization_id_value bigint;
  incoming jsonb;
  source_election jsonb;
  staged public.officer_new_roster%rowtype;
  winner jsonb;
  existing_elected public.officers%rowtype;
  election_id_value integer;
  outgoing_count integer := 0;
  elected_count integer := 0;
  appointed_count integer := 0;
begin
  organization_id_value := private.kandid_assert_officer_org_scope(p_organization_id);
  perform pg_catalog.pg_advisory_xact_lock(913027, organization_id_value::integer);
  incoming := public.kandid_get_incoming_leadership(organization_id_value);
  source_election := incoming->'source_election';
  if source_election is not null and source_election <> 'null'::jsonb then
    election_id_value := (source_election->>'election_id')::integer;
  end if;

  if election_id_value is not null and exists (
    select 1 from public.officer_leadership_releases r
    where r.organization_id = organization_id_value and r.election_id = election_id_value
  ) then
    raise exception using errcode = '23505', message = 'Officers for this election have already been released.';
  end if;

  if exists (
    select 1 from public.officer_new_roster n
    where n.organization_id = organization_id_value
      and n.selection_type = 'elected'
      and n.election_id is distinct from election_id_value
  ) then
    raise exception using errcode = '42501', message = 'Remove officers prepared for a prior election before release.';
  end if;

  select count(*) filter (where n.selection_type = 'elected')::integer,
         count(*) filter (where n.selection_type = 'appointed')::integer
    into elected_count, appointed_count
  from public.officer_new_roster n
  where n.organization_id = organization_id_value
    and (n.election_id is not distinct from election_id_value or (n.selection_type = 'appointed' and n.election_id is null));
  if elected_count + appointed_count = 0 then
    raise exception using errcode = '22023', message = 'Add at least one new officer before release.';
  end if;

  -- Revalidate each manually selected elected candidate against the latest
  -- server-computed unique winner and each appointee against current eligibility.
  for staged in
    select n.* from public.officer_new_roster n
    where n.organization_id = organization_id_value
      and (n.election_id is not distinct from election_id_value or (n.selection_type = 'appointed' and n.election_id is null))
    order by n.created_at, n.id
    for update
  loop
    if staged.selection_type = 'elected' then
      select value into winner
      from pg_catalog.jsonb_array_elements(coalesce(incoming->'available_winners', '[]'::jsonb))
      where (value->>'candidate_id')::integer = staged.candidate_id
        and (value->>'position_id')::integer = staged.position_id;
      if not found or (winner->>'student_id')::integer is distinct from staged.student_id
         or (winner->>'already_added')::boolean is distinct from true then
        raise exception using errcode = '42501', message = 'A staged elected officer is no longer a verified winner in the latest election.';
      end if;
    else
      perform private.kandid_assert_eligible_officer_student(organization_id_value, staged.student_id);
    end if;
  end loop;

  insert into public.officer_leadership_releases (
    organization_id, election_id, released_by, elected_count, appointed_count
  ) values (organization_id_value, election_id_value, auth.uid(), elected_count, appointed_count);

  perform pg_catalog.set_config('kandid.allow_leadership_turnover', 'on', true);
  update public.officers o
  set is_current = false,
      term_end = coalesce(o.term_end, pg_catalog.timezone('Asia/Manila', pg_catalog.clock_timestamp())::date)
  where o.organization_id = organization_id_value and o.is_current;
  get diagnostics outgoing_count = row_count;

  for staged in
    select n.* from public.officer_new_roster n
    where n.organization_id = organization_id_value
      and (n.election_id is not distinct from election_id_value or (n.selection_type = 'appointed' and n.election_id is null))
    order by n.created_at, n.id
  loop
    if staged.selection_type = 'elected' then
      select o.* into existing_elected
      from public.officers o
      where o.election_id = election_id_value
        and o.position_id = staged.position_id
        and o.selection_type = 'elected'
      for update;
      if found then
        if existing_elected.candidate_id is distinct from staged.candidate_id
           or existing_elected.organization_id is distinct from organization_id_value then
          raise exception using errcode = '55000', message = 'An existing elected record conflicts with the verified winner.';
        end if;
        update public.officers o set is_current = true
        where o.id = existing_elected.id;
      else
        perform public.kandid_create_elected_officer(
          staged.candidate_id,
          staged.service || pg_catalog.jsonb_build_object('is_current', true)
        );
      end if;
    else
      perform public.kandid_create_appointed_officer(
        organization_id_value,
        staged.student_id,
        staged.position_title,
        staged.service || pg_catalog.jsonb_build_object('is_current', true)
      );
    end if;
  end loop;

  delete from public.officer_new_roster n
  where n.organization_id = organization_id_value
    and (n.election_id is not distinct from election_id_value or (n.selection_type = 'appointed' and n.election_id is null));

  return pg_catalog.jsonb_build_object(
    'released', true,
    'organization_id', organization_id_value,
    'election_id', election_id_value,
    'outgoing_count', outgoing_count,
    'elected_count', elected_count,
    'appointed_count', appointed_count
  );
end;
