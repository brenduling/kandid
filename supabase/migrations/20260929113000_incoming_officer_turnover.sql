create or replace function public.kandid_update_new_officer(
  p_new_officer_id bigint,
  p_organization_id bigint,
  p_changes jsonb
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = pg_catalog
as $function$
declare
  organization_id_value bigint;
  staged public.officer_new_roster%rowtype;
  service_value jsonb;
  position_title_value text;
  updated jsonb;
begin
  organization_id_value := private.kandid_assert_officer_org_scope(p_organization_id);
  perform pg_catalog.pg_advisory_xact_lock(913027, organization_id_value::integer);
  select n.* into staged
  from public.officer_new_roster n
  where n.id = p_new_officer_id and n.organization_id = organization_id_value
  for update;
  if not found then
    raise exception using errcode = 'P0002', message = 'New officer was not found.';
  end if;
  if p_changes is null or pg_catalog.jsonb_typeof(p_changes) <> 'object'
     or exists (
       select 1 from pg_catalog.jsonb_object_keys(p_changes) as keys(key)
       where key not in ('position_title', 'service')
     ) then
    raise exception using errcode = '22023', message = 'New officer changes contain unsupported fields.';
  end if;
  if staged.selection_type = 'elected' and p_changes ? 'position_title' then
    raise exception using errcode = '42501', message = 'Elected position and provenance are read-only.';
  end if;
  position_title_value := staged.position_title;
  if p_changes ? 'position_title' then
    position_title_value := nullif(pg_catalog.btrim(p_changes->>'position_title'), '');
    if position_title_value is null or pg_catalog.length(position_title_value) > 160 then
      raise exception using errcode = '22023', message = 'A valid appointed position title is required.';
    end if;
  end if;
  service_value := staged.service;
  if p_changes ? 'service' then
    service_value := private.kandid_sanitize_officer_service(p_changes->'service');
  end if;

  update public.officer_new_roster n
  set position_title = position_title_value, service = service_value
  where n.id = staged.id
  returning pg_catalog.jsonb_build_object('id', n.id, 'selection_type', n.selection_type, 'position_title', n.position_title) into updated;
  return updated;
end;
$function$;

