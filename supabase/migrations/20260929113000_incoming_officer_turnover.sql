create or replace function private.kandid_guard_leadership_turnover()
returns trigger
language plpgsql
set search_path = pg_catalog
as $function$
begin
  if tg_op = 'INSERT' then
    if new.is_current
       and pg_catalog.current_setting('kandid.allow_leadership_turnover', true) is distinct from 'on' then
      raise exception using errcode = '42501', message = 'Current leadership changes must use the release workflow.';
    end if;
    return new;
  end if;

  if new.is_current is distinct from old.is_current
     and pg_catalog.current_setting('kandid.allow_leadership_turnover', true) is distinct from 'on' then
    raise exception using errcode = '42501', message = 'Current leadership changes must use the release workflow.';
  end if;
  return new;
end;
$function$;

