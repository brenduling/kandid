create or replace function private.kandid_assert_officer_org_scope(p_organization_id bigint)
returns bigint
language plpgsql
stable
security definer
set search_path = pg_catalog
as $function$
declare
  caller_uid uuid := auth.uid();
  admin_row record;
  organization_id_value bigint;
begin
  if caller_uid is null then
    raise exception using errcode = '28000', message = 'Authentication required.';
  end if;

  select a.role, a.organization_id into admin_row
  from public.admin_users a
  where a.auth_user_id = caller_uid
    and a.status = 'active'
    and a.role in ('electoral_board', 'super_admin')
  limit 1;
  if not found then
    raise exception using errcode = '42501', message = 'Active administrator authorization required.';
  end if;

  if admin_row.role = 'electoral_board' then
    organization_id_value := admin_row.organization_id;
    if organization_id_value is null
       or (p_organization_id is not null and p_organization_id is distinct from organization_id_value) then
      raise exception using errcode = '42501', message = 'Organization is outside your assignment.';
    end if;
  else
    organization_id_value := p_organization_id;
  end if;

  if organization_id_value is null then
    raise exception using errcode = '22023', message = 'Organization is required.';
  end if;
  if not exists (select 1 from public.organizations o where o.id = organization_id_value) then
    raise exception using errcode = '22023', message = 'Organization not found.';
  end if;
  return organization_id_value;
end;
$function$;

create or replace function private.kandid_assert_eligible_officer_student(
  p_organization_id bigint,
  p_student_id integer
)
returns void
language plpgsql
volatile
security definer
set search_path = pg_catalog
as $function$
declare
  student_status text;
  active_term_id integer;
  eligible boolean;
begin
  select s.status into student_status
  from public.students s
  where s.id = p_student_id
  for share;
  if not found or student_status <> 'active' then
    raise exception using errcode = '42501', message = 'Select an active eligible organization student.';
  end if;

  select t.id into active_term_id
  from public.academic_terms t
  where t.status = 'active'
  order by t.created_at desc, t.id desc
  limit 1;
  if active_term_id is null then
    raise exception using errcode = '42501', message = 'Active academic-term eligibility could not be verified.';
  end if;

  select participation.allowed into eligible
  from public.resolve_student_organization_participation(
    p_student_id, p_organization_id::integer, active_term_id
  ) participation
  limit 1;
  if eligible is distinct from true then
    raise exception using errcode = '42501', message = 'Student is not eligible for this organization.';
  end if;
end;
$function$;

create or replace function private.kandid_sanitize_officer_service(p_service jsonb)
returns jsonb
language plpgsql
immutable
set search_path = pg_catalog
as $function$
declare
  term_label_value text;
  term_start_value date;
  term_end_value date;
  photo_value text;
  remarks_value text;
begin
  if p_service is null or pg_catalog.jsonb_typeof(p_service) <> 'object'
     or exists (
       select 1 from pg_catalog.jsonb_object_keys(coalesce(p_service, '{}'::jsonb)) as keys(key)
       where key not in ('term_label', 'term_start', 'term_end', 'photo_url', 'remarks')
     ) then
    raise exception using errcode = '22023', message = 'Invalid officer service fields.';
  end if;

  term_label_value := nullif(pg_catalog.btrim(p_service->>'term_label'), '');
  photo_value := nullif(pg_catalog.btrim(p_service->>'photo_url'), '');
  remarks_value := nullif(pg_catalog.btrim(p_service->>'remarks'), '');
  if (term_label_value is not null and pg_catalog.length(term_label_value) > 120)
     or (photo_value is not null and pg_catalog.length(photo_value) > 2048)
     or (remarks_value is not null and pg_catalog.length(remarks_value) > 2000) then
    raise exception using errcode = '22023', message = 'Officer service details are too long.';
  end if;
  if nullif(p_service->>'term_start', '') is not null then
    term_start_value := (p_service->>'term_start')::date;
  end if;
  if nullif(p_service->>'term_end', '') is not null then
    term_end_value := (p_service->>'term_end')::date;
  end if;
  return pg_catalog.jsonb_strip_nulls(pg_catalog.jsonb_build_object(
    'term_label', term_label_value,
    'term_start', term_start_value,
    'term_end', term_end_value,
    'photo_url', photo_value,
    'remarks', remarks_value
  ));
end;
$function$;

