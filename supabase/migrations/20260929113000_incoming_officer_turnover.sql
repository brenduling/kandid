create or replace function public.kandid_get_incoming_leadership(p_organization_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog
as $function$
declare
  organization_id_value bigint;
  winners jsonb;
  selected_election jsonb;
  position_row jsonb;
  candidate_row record;
  available_winners jsonb := '[]'::jsonb;
  unresolved_rows jsonb := '[]'::jsonb;
  new_officer_rows jsonb;
begin
  organization_id_value := private.kandid_assert_officer_org_scope(p_organization_id);
  winners := public.kandid_get_officer_winners(null, organization_id_value);
  selected_election := winners->'selected_election';

  if selected_election is null or selected_election = 'null'::jsonb then
    select coalesce(pg_catalog.jsonb_agg(
      pg_catalog.jsonb_build_object(
        'id', n.id,
        'selection_type', n.selection_type,
        'election_id', n.election_id,
        'candidate_id', n.candidate_id,
        'position_id', n.position_id,
        'student_id', n.student_id,
        'student_name', nullif(pg_catalog.btrim(pg_catalog.concat_ws(' ', s.first_name, s.last_name)), ''),
        'student_number', s.student_number,
        'photo_url', coalesce(nullif(pg_catalog.btrim(n.service->>'photo_url'), ''), s.photo_url),
        'position_title', n.position_title,
        'service', n.service
      ) order by n.created_at, n.id
    ), '[]'::jsonb)
    into new_officer_rows
    from public.officer_new_roster n
    join public.students s on s.id = n.student_id
    where n.organization_id = organization_id_value;

    return pg_catalog.jsonb_build_object(
      'organization_id', organization_id_value,
      'source_election', null,
      'available_winners', '[]'::jsonb,
      'unresolved', '[]'::jsonb,
      'new_officers', new_officer_rows
    );
  end if;

  for position_row in
    select value from pg_catalog.jsonb_array_elements(coalesce(selected_election->'positions', '[]'::jsonb))
  loop
    if position_row->>'outcome' = 'winner' then
      select c.id as candidate_id, c.student_id, c.position_id,
             p.name as position_title, s.first_name, s.last_name,
             s.student_number, coalesce(c.photo, s.photo_url) as photo_url
        into candidate_row
      from public.candidates c
      join public.positions p on p.id = c.position_id
      join public.students s on s.id = c.student_id
      where c.id = (position_row->>'candidate_id')::integer
        and p.id = (position_row->>'position_id')::integer
        and p.election_id = (selected_election->>'election_id')::integer;
      if not found then
        raise exception using errcode = '55000', message = 'A published winner is no longer linked to a valid student position.';
      end if;

      available_winners := available_winners || pg_catalog.jsonb_build_array(
        pg_catalog.jsonb_build_object(
          'candidate_id', candidate_row.candidate_id,
          'student_id', candidate_row.student_id,
          'position_id', candidate_row.position_id,
          'position_title', candidate_row.position_title,
          'student_name', nullif(pg_catalog.btrim(pg_catalog.concat_ws(' ', candidate_row.first_name, candidate_row.last_name)), ''),
          'student_number', candidate_row.student_number,
          'photo_url', candidate_row.photo_url,
          'already_added', exists (
            select 1 from public.officer_new_roster n
            where n.organization_id = organization_id_value
              and n.student_id = candidate_row.student_id
          )
        )
      );
    else
      unresolved_rows := unresolved_rows || pg_catalog.jsonb_build_array(position_row);
    end if;
  end loop;

  select coalesce(pg_catalog.jsonb_agg(
    pg_catalog.jsonb_build_object(
      'id', n.id,
      'selection_type', n.selection_type,
      'election_id', n.election_id,
      'candidate_id', n.candidate_id,
      'position_id', n.position_id,
      'student_id', n.student_id,
      'student_name', nullif(pg_catalog.btrim(pg_catalog.concat_ws(' ', s.first_name, s.last_name)), ''),
      'student_number', s.student_number,
      'photo_url', coalesce(nullif(pg_catalog.btrim(n.service->>'photo_url'), ''), s.photo_url),
      'position_title', n.position_title,
      'service', n.service
    ) order by n.created_at, n.id
  ), '[]'::jsonb)
  into new_officer_rows
  from public.officer_new_roster n
  join public.students s on s.id = n.student_id
  where n.organization_id = organization_id_value;

  return pg_catalog.jsonb_build_object(
    'organization_id', organization_id_value,
    'source_election', selected_election - 'positions',
    'available_winners', available_winners,
    'unresolved', unresolved_rows,
    'new_officers', new_officer_rows
  );
end;
$function$;

create or replace function public.kandid_add_incoming_elected_officer(
  p_organization_id bigint,
  p_candidate_id integer,
  p_service jsonb default '{}'::jsonb
