-- Prepared officers are kept outside public.officers. Current/Past state only
-- changes when the complete manually assembled roster is released.
create table public.officer_new_roster (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references public.organizations(id) on delete restrict,
  election_id integer references public.elections(id) on delete restrict,
  selection_type text not null check (selection_type in ('elected', 'appointed')),
  student_id integer not null references public.students(id) on delete restrict,
  candidate_id integer references public.candidates(id) on delete restrict,
  position_id integer references public.positions(id) on delete restrict,
  position_title text not null,
  service jsonb not null default '{}'::jsonb,
  created_by uuid not null,
  created_at timestamptz not null default pg_catalog.clock_timestamp(),
  constraint officer_new_roster_position_check
    check (pg_catalog.btrim(position_title) <> '' and pg_catalog.length(position_title) <= 160),
  constraint officer_new_roster_service_check
    check (pg_catalog.jsonb_typeof(service) = 'object'),
  constraint officer_new_roster_provenance_check
    check (
      (selection_type = 'elected' and election_id is not null and candidate_id is not null and position_id is not null)
      or (selection_type = 'appointed' and election_id is null and candidate_id is null and position_id is null)
    )
);

create unique index officer_new_roster_one_student_uidx
  on public.officer_new_roster (organization_id, student_id);

create index officer_new_roster_order_idx
  on public.officer_new_roster (organization_id, election_id, created_at, id);

create table public.officer_leadership_releases (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references public.organizations(id) on delete restrict,
  election_id integer references public.elections(id) on delete restrict,
  released_by uuid not null,
  released_at timestamptz not null default pg_catalog.clock_timestamp(),
  elected_count integer not null,
  appointed_count integer not null,
  constraint officer_leadership_releases_counts_check
    check (elected_count >= 0 and appointed_count >= 0)
);

create unique index officer_leadership_releases_election_uidx
  on public.officer_leadership_releases (organization_id, election_id)
  where election_id is not null;

alter table public.officer_new_roster enable row level security;
alter table public.officer_leadership_releases enable row level security;
revoke all on table public.officer_new_roster from public, anon, authenticated, service_role;
