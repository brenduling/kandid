do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'elections_student_result_visibility_check'
  ) then
    alter table public.elections
      add constraint elections_student_result_visibility_check
      check (student_result_visibility in ('hidden', 'realtime'));
  end if;
end
$$;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'elections_voting_access_mode_check'
  ) then
    alter table public.elections
      add constraint elections_voting_access_mode_check
      check (
        voting_access_mode in (
          'anywhere',
          'onsite_qr',
          'precinct_qr',
          'batch_qr',
          'location_range'
        )
      );
